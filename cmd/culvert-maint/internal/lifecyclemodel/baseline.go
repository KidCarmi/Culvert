// The reviewed baseline closes a gap the property statuses cannot: every property is
// `proposed` or `open`, so with -fail-only-approved a property that turns from PASS to FAIL
// (or FAIL to PASS) never changes the exit code, and a pull request that edits the
// implementation AND model.go together keeps every conformance vector green. The baseline
// records what the model said at the last reviewed change — each verdict, each shortest
// counterexample, the state-space size and every derived vector, one human-readable line
// each — so any such change shows up as DRIFT until the same pull request regenerates
// baseline.json and a reviewer sees the line-by-line diff.
//
// Drift is not a verdict on correctness and does not approve or reject a property. It
// says only "the modelled behaviour differs from the last reviewed baseline".

//go:embed baseline.json
var baselineJSON []byte

// EmbeddedBaselineJSON returns the reviewed baseline compiled into the binary.
func EmbeddedBaselineJSON() []byte { return baselineJSON }

// BaselineProperty is one property's recorded verdict.
type BaselineProperty struct {
	ID        string   `json:"id"`
	Status    string   `json:"status"`
	Verdict   string   `json:"verdict"`
	Exercised int      `json:"exercised,omitempty"`
	Trace     []string `json:"trace,omitempty"`
}

// ReconcileFingerprint pins the reconcile decision table, which is too large to list. The
// hash covers the input domains, the reason codes AND the action paired with each reason:
// the per-input code alone indexes a reason, so a change of a reason's action would
// otherwise leave it unchanged. VerdictCounts is keyed "action/reason" and compared too.
type ReconcileFingerprint struct {
	Inputs        int            `json:"inputs"`
	SHA256        string         `json:"sha256"`
	VerdictCounts map[string]int `json:"verdict_counts"`
}

// Baseline is the content of baseline.json.
type Baseline struct {
	Note        string               `json:"note"`
	PropsSHA256 string               `json:"props_sha256"`
	Stats       Stats                `json:"stats"`
	Properties  []BaselineProperty   `json:"properties"`
	Reconcile   ReconcileFingerprint `json:"reconcile"`
	Apply       []string             `json:"apply"`
	Crash       []string             `json:"crash"`
}

const baselineNote = "Reviewed lifecycle-model baseline. Generated by test/lifecycle-conformance/update-baseline.sh; " +
	"never edit by hand. A diff here is a change in modelled behaviour: review it line by line."

// ComputeBaseline builds the baseline from a complete, non-vacuous check.
func ComputeBaseline(propsSHA string, stats Stats, results []Result) Baseline {
	b := Baseline{Note: baselineNote, PropsSHA256: propsSHA, Stats: stats}
	for i := range results {
		r := &results[i]
		bp := BaselineProperty{ID: r.ID, Status: r.Status, Verdict: r.Verdict}
		switch r.Verdict {
		case VerdictPass:
			bp.Exercised = r.Exercised
		case VerdictFail:
			bp.Trace = append([]string{}, r.Trace...)
		}
		b.Properties = append(b.Properties, bp)
	}
	sort.Slice(b.Properties, func(i, j int) bool { return b.Properties[i].ID < b.Properties[j].ID })
	apply, crash := Vectors()
	for i := range apply {
		b.Apply = append(b.Apply, ApplyLine(&apply[i]))
	}
	for i := range crash {
		b.Crash = append(b.Crash, CrashLine(&crash[i]))
	}
	b.Reconcile = reconcileFingerprint(GenReconcileVectors())
	return b
}

func reconcileFingerprint(rv *ReconcileVectors) ReconcileFingerprint {
	raw, err := json.Marshal(rv) // domains, reasons, actions and every per-input code
	if err != nil {
		panic(err) // plain data: cannot fail
	}
	sum := sha256.Sum256(raw)
	counts := map[string]int{}
	for n := range rv.Expected {
		action, reason := rv.Verdict(n)
		counts[action+"/"+reason]++
	}
	return ReconcileFingerprint{Inputs: len(rv.Expected), SHA256: hex.EncodeToString(sum[:]), VerdictCounts: counts}
}

func sameCounts(a, b map[string]int) bool {
	if len(a) != len(b) {
		return false
	}
	for k, v := range a {
		if b[k] != v {
			return false
		}
	}
	return true
}

func paramsLine(p Params) string {
	return fmt.Sprintf("prior=%s same=%t backup=%t rb=%t th=%t ph=%t", p.Prior, p.Same, p.Backup, p.RB, p.TH, p.PH)
}

// faultsLine keeps only the stages whose outcome is not ok/skip: the injected faults.
func faultsLine(script []ScriptStep) string {
	var parts []string
	for _, st := range script {
		if st[1] != evOK && st[1] != evSkip {
			parts = append(parts, st[0]+"="+st[1])
		}
	}
	if len(parts) == 0 {
		return "no faults"
	}
	return strings.Join(parts, " > ")
}

func planLine(plan []PlanEntry) string {
	parts := make([]string, 0, len(plan))
	for _, p := range plan {
		parts = append(parts, fmt.Sprintf("%s#%d=%s", p.Cmd, p.N, p.Mode))
	}
	return "plan=" + strings.Join(parts, ",")
}

// ApplyLine renders one apply vector as a single reviewable line. It must carry EVERY field
// of the expectation the conformance suite compares with the real code: a field left out is
// a field a code+model co-change can alter without drift (independent review: an omitted
// upgrade_succeeded let "rolled back" be reported as "succeeded" with exit 0).
// TestApplyLine_CoversEveryExpectationField enforces it.
func ApplyLine(v *ApplyVector) string {
	e := &v.Expect
	return fmt.Sprintf("%s | %s | op=%s reason=%s upgrade_ok=%t running=%s tag=%s rb_att=%t rb_ok=%t rb_skip=%s tag_ahead=%t journal_empty=%t | %s | %s",
		paramsLine(v.Params), faultsLine(v.Script), e.Op, e.Reason, e.UpgradeSucceeded, e.Running, e.Tag, e.RollbackAttempted,
		e.RollbackSucceeded, e.RollbackSkippedReason, e.TagAhead, e.JournalEmpty, strings.Join(e.Cmds, ","), planLine(v.Plan))
}

// CrashLine renders one crash vector as a single reviewable line.
func CrashLine(v *CrashVector) string {
	e, r := &v.Expect, &v.Expect.Record
	block := v.Block.Cmd + "#" + strconv.Itoa(v.Block.N)
	if v.Block.AfterTag {
		block += "+tag"
	}
	if v.Block.AfterUp {
		block += "+up"
	}
	return fmt.Sprintf("%s | %s | block=%s | phase=%s tag=%s running=%s rec_phase=%s prior_ref=%t prior_id=%s target_ref=%t target_id=%s | %s/%s | %s | %s",
		paramsLine(v.Params), faultsLine(v.Script), block, e.Phase, e.Tag, e.Running, r.Phase, r.PriorRef, r.PriorID,
		r.TargetRef, r.TargetID, e.ReconcileAction, e.ReconcileReason, strings.Join(e.CmdsBeforeBlock, ","), planLine(v.Plan))
}

// ParseBaseline decodes a baseline file. An empty or unparsable baseline is an error,
// never "no drift".
func ParseBaseline(raw []byte) (Baseline, error) {
	var b Baseline
	if len(raw) == 0 {
		return b, errors.New("baseline is empty")
	}
	if err := json.Unmarshal(raw, &b); err != nil {
		return b, fmt.Errorf("parse baseline: %w", err)
	}
	if b.PropsSHA256 == "" || b.Stats.States == 0 || len(b.Properties) == 0 || len(b.Apply) == 0 ||
		len(b.Crash) == 0 || b.Reconcile.Inputs == 0 {
		return b, errors.New("baseline is incomplete: refusing to compare against it")
	}
	return b, nil
}

// maxDriftLines bounds how many differing vector lines are printed per section.
const maxDriftLines = 8

// CompareBaseline returns one human-readable line per difference; nil means no drift.
func CompareBaseline(want, got Baseline) []string {
	var d []string
	if want.PropsSHA256 != got.PropsSHA256 {
		d = append(d, fmt.Sprintf("properties.json changed: baseline sha256 %.16s, now %.16s", want.PropsSHA256, got.PropsSHA256))
	}
	if want.Stats != got.Stats {
		d = append(d, fmt.Sprintf("state space changed: baseline %d states / %d transitions, now %d / %d",
			want.Stats.States, want.Stats.Transitions, got.Stats.States, got.Stats.Transitions))
	}
	d = append(d, compareProperties(want.Properties, got.Properties)...)
	if want.Reconcile.Inputs != got.Reconcile.Inputs || want.Reconcile.SHA256 != got.Reconcile.SHA256 ||
		!sameCounts(want.Reconcile.VerdictCounts, got.Reconcile.VerdictCounts) {
		d = append(d, fmt.Sprintf("reconcile decision table changed: baseline %d inputs sha256 %.16s, now %d sha256 %.16s; verdict counts %v -> %v",
			want.Reconcile.Inputs, want.Reconcile.SHA256, got.Reconcile.Inputs, got.Reconcile.SHA256,
			want.Reconcile.VerdictCounts, got.Reconcile.VerdictCounts))
	}
	d = append(d, compareLines("apply vector", want.Apply, got.Apply)...)
	d = append(d, compareLines("crash vector", want.Crash, got.Crash)...)
	return d
}

func compareProperties(want, got []BaselineProperty) []string {
	var d []string
	w := map[string]BaselineProperty{}
	for _, p := range want {
		w[p.ID] = p
	}
	seen := map[string]bool{}
	for _, g := range got {
		seen[g.ID] = true
		p, ok := w[g.ID]
		switch {
		case !ok:
			d = append(d, fmt.Sprintf("property %s is new (verdict %s); record it in the baseline", g.ID, g.Verdict))
		case p.Verdict != g.Verdict:
			d = append(d, fmt.Sprintf("property %s verdict %s -> %s", g.ID, p.Verdict, g.Verdict))
		case p.Status != g.Status:
			d = append(d, fmt.Sprintf("property %s status %s -> %s", g.ID, p.Status, g.Status))
		case p.Exercised != g.Exercised:
			d = append(d, fmt.Sprintf("property %s exercised %d -> %d states/edges", g.ID, p.Exercised, g.Exercised))
		case strings.Join(p.Trace, ">") != strings.Join(g.Trace, ">"):
			d = append(d, fmt.Sprintf("property %s counterexample %v -> %v", g.ID, p.Trace, g.Trace))
		}
	}
	for _, p := range want {
		if !seen[p.ID] {
			d = append(d, fmt.Sprintf("property %s (baseline verdict %s) is no longer evaluated", p.ID, p.Verdict))
		}
	}
	return d
}

// compareLines reports lines removed from and added to a vector set (as multisets, so a
// reordering alone is not drift but a duplicated or dropped vector is).
func compareLines(what string, want, got []string) []string {
	count := map[string]int{}
	for _, l := range want {
		count[l]++
	}
	for _, l := range got {
		count[l]--
	}
	var removed, added []string
	for l, n := range count {
		for ; n > 0; n-- {
			removed = append(removed, l)
		}
		for ; n < 0; n++ {
			added = append(added, l)
		}
	}
	if len(removed) == 0 && len(added) == 0 {
		return nil
	}
	sort.Strings(removed)
	sort.Strings(added)
	d := []string{fmt.Sprintf("%s set changed: %d -> %d vectors, %d removed, %d added", what, len(want), len(got), len(removed), len(added))}
	for i, l := range removed {
		if i == maxDriftLines {
			d = append(d, fmt.Sprintf("  ... %d more removed", len(removed)-i))
			break
		}
		d = append(d, "  - "+l)
	}
	for i, l := range added {
		if i == maxDriftLines {
			d = append(d, fmt.Sprintf("  ... %d more added", len(added)-i))
			break
		}
		d = append(d, "  + "+l)
	}
	return d
}

// WriteBaselineFile writes b to path in the reviewed, line-per-vector layout.
func WriteBaselineFile(path string, b Baseline) error {
	out, err := MarshalReviewable(b)
	if err != nil {
		return err
	}
	return os.WriteFile(path, out, 0o600)
}

// MarshalReviewable is indented JSON without HTML escaping, so "->" and "&&" stay readable
// in a pull-request diff.
func MarshalReviewable(v any) ([]byte, error) {
	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetEscapeHTML(false)
	enc.SetIndent("", " ")
	if err := enc.Encode(v); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}
