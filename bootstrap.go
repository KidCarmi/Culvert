// ── HTTP handlers ──────────────────────────────────────────────────────

// apiBootstrapRouter routes bootstrap requests to either the shell script
// or the docker-compose.yml handler based on the path suffix.
func apiBootstrapRouter(w http.ResponseWriter, r *http.Request) {
	if strings.HasSuffix(r.URL.Path, "/compose") {
		apiBootstrapCompose(w, r)
	} else {
		apiBootstrapScript(w, r)
	}
}

// apiBootstrapScript serves the install script for a given enrollment token.
// GET /api/cluster/bootstrap/{token} — returns shell script (no auth required,
// but the token itself is the auth — it's single-use and time-limited).
func apiBootstrapScript(w http.ResponseWriter, r *http.Request) {
	if r.Method != http.MethodGet {
		http.Error(w, "method not allowed", http.StatusMethodNotAllowed)
		return
	}

	token := extractBootstrapToken(r.URL.Path, "/api/cluster/bootstrap/")
	if token == "" || strings.Contains(token, "/") {
		http.Error(w, "invalid token path", http.StatusBadRequest)
		return
	}

	// Verify token exists (don't consume it — compose download needs it too).
	if !globalClusterStore.TokenExists(token) {
		http.Error(w, "invalid or expired token", http.StatusNotFound)
		return
	}

	// Derive CP base URL from request.
	cpBase := cpBaseURL(r)

	w.Header().Set("Content-Type", "text/x-shellscript; charset=utf-8")
	w.Header().Set("Content-Disposition", "inline; filename=culvert-bootstrap.sh")
	err := bootstrapScriptTmpl.Execute(w, map[string]string{
		"CPHost":    r.Host,
		"CPBase":    cpBase,
		"TokenPath": token,
	})
	if err != nil {
		logger.Printf("Bootstrap: script template error: %v", err)
	}
}

// apiBootstrapCompose serves the docker-compose.yml for a given enrollment token.
// GET /api/cluster/bootstrap/{token}/compose — returns YAML (no auth required,
// token is the auth).
func apiBootstrapCompose(w http.ResponseWriter, r *http.Request) {
	if r.Method != http.MethodGet {
		http.Error(w, "method not allowed", http.StatusMethodNotAllowed)
		return
	}

	// Extract token — path is /api/cluster/bootstrap/{token}/compose
	path := r.URL.Path
	const prefix = "/api/cluster/bootstrap/"
	const suffix = "/compose"
	if !strings.HasPrefix(path, prefix) || !strings.HasSuffix(path, suffix) {
		http.Error(w, "invalid path", http.StatusBadRequest)
		return
	}
	token := path[len(prefix) : len(path)-len(suffix)]
	if token == "" || strings.Contains(token, "/") {
		http.Error(w, "invalid token", http.StatusBadRequest)
		return
	}

	// Verify token exists (don't consume — enrollment RPC consumes it).
	if !globalClusterStore.TokenExists(token) {
		http.Error(w, "invalid or expired token", http.StatusNotFound)
		return
	}

	// Build enrollment URL — derive CP host from the HTTP request so the
	// generated docker-compose.yml works from remote machines (not just localhost).
	cpAddr := enrollmentCPAddr(r, clusterRole.grpcAddr)
	caFP := globalClusterCA.CACertFingerprint()
	enrollURL := fmt.Sprintf("culvert://enroll/%s/%s?ca-fp=sha256:%s", cpAddr, token, caFP)

	w.Header().Set("Content-Type", "application/x-yaml; charset=utf-8")
	w.Header().Set("Content-Disposition", "inline; filename=docker-compose.yml")
	err := bootstrapComposeTmpl.Execute(w, map[string]string{
		"Image":        bootstrapImage(),
		"UpdaterImage": updaterImage(),
		"EnrollURL":    enrollURL,
	})
	if err != nil {
		logger.Printf("Bootstrap: compose template error: %v", err)
	}
}

// ── Helpers ────────────────────────────────────────────────────────────

// extractBootstrapToken extracts the token segment from a bootstrap URL path.
// For /api/cluster/bootstrap/abc123 → "abc123"
// For /api/cluster/bootstrap/abc123/compose → "abc123"
func extractBootstrapToken(path, prefix string) string {
	if !strings.HasPrefix(path, prefix) {
		return ""
	}
	rest := path[len(prefix):]
	// Strip trailing /compose if present
	rest = strings.TrimSuffix(rest, "/compose")
	// Must be a single segment (no slashes)
	if strings.Contains(rest, "/") {
		return ""
	}
	return rest
}

// cpBaseURL derives the CP's external base URL from the incoming request.
func cpBaseURL(r *http.Request) string {
	scheme := "https"
	if r.TLS == nil {
		scheme = "http"
	}
	host := r.Host
	if trustForwardedHeaders {
		if fp := r.Header.Get("X-Forwarded-Proto"); fp == "http" || fp == "https" {
			scheme = fp
		}
		if fh := r.Header.Get("X-Forwarded-Host"); fh != "" {
			host = fh
		}
	}
	return scheme + "://" + host
}

// enrollmentCPAddr derives the gRPC Control Plane address for the enrollment URL.
// Uses the HTTP request's host (the IP/hostname the admin used to access the UI)
// combined with the gRPC port from the configured listen address.
// IPv6-safe: strips brackets before net.JoinHostPort to prevent double-bracketing.
func enrollmentCPAddr(r *http.Request, grpcListenAddr string) string {
	// If grpcAddr already contains a routable host (not just :port), use it as-is.
	if grpcListenAddr != "" {
		gHost, _, err := net.SplitHostPort(grpcListenAddr)
		if err == nil && gHost != "" && gHost != "0.0.0.0" && gHost != "::" {
			return grpcListenAddr
		}
	}

	// Derive host from the HTTP request.
	cpHost := r.Host
	if trustForwardedHeaders {
		if fh := r.Header.Get("X-Forwarded-Host"); fh != "" {
			cpHost = fh
		}
	}

	// Extract host — IPv6-safe (r.Host for IPv6 is [::1]:port).
	host, _, err := net.SplitHostPort(cpHost)
	if err != nil {
		// No port or bare host — strip brackets to prevent [[::1]]:port
		host = strings.Trim(cpHost, "[]")
	}

	// Extract gRPC port from the listen address.
	_, grpcPort, err := net.SplitHostPort(grpcListenAddr)
	if err != nil || grpcPort == "" {
		grpcPort = "50051"
	}

	// net.JoinHostPort adds brackets for IPv6 automatically.
	return net.JoinHostPort(host, grpcPort)
}

