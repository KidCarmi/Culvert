package main

// ─── One-Click Node Bootstrap ──────────────────────────────────────────────
//
// Serves a shell script and docker-compose.yml that fully automate DP node
// deployment. The admin generates an enrollment token in the GUI; the GUI
// shows a single curl|bash command. On the target server, the script:
//
//  1. Installs Docker Engine + Compose plugin if missing
//  2. Creates a working directory (/opt/culvert-dp)
//  3. Downloads docker-compose.yml from the CP (pre-configured)
//  4. Runs docker compose up -d
//  5. The DP container enrolls with the CP automatically on first boot
//

import (
	"encoding/json"
	"fmt"
	"net"
	"net/http"
	"os"
	"strings"
	"text/template"
)

// defaultImage is the default container image; overridden by registry settings.
const defaultImage = "ghcr.io/kidcarmi/culvert"

// bootstrapImage returns the image reference for DP nodes, checking registry
// settings first, falling back to the default ghcr.io image with current version.
func bootstrapImage() string {
	data, err := os.ReadFile(registrySettingsFile)
	if err == nil && len(data) > 0 {
		var s map[string]string
		if json.Unmarshal(data, &s) == nil && s["registry_url"] != "" {
			img := s["registry_url"]
			if version != "dev" {
				img += ":" + version
			} else {
				img += ":latest"
			}
			return img
		}
	}
	if version != "dev" {
		return defaultImage + ":" + version
	}
	return defaultImage + ":latest"
}

// updaterImage returns the updater sidecar image reference.
func updaterImage() string {
	data, err := os.ReadFile(registrySettingsFile)
	if err == nil && len(data) > 0 {
		var s map[string]string
		if json.Unmarshal(data, &s) == nil && s["registry_url"] != "" {
			base := s["registry_url"]
			// Derive updater image: append -updater to the base name
			if version != "dev" {
				return base + "-updater:" + version
			}
			return base + "-updater:latest"
		}
	}
	base := defaultImage + "-updater"
	if version != "dev" {
		return base + ":" + version
	}
	return base + ":latest"
}

